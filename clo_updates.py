"""Selective garment replacement. Originals survive staging and property verification."""
import json
import math

from clo_adapter import create_batch, backup_project
from clo_curves import encode
from contour_engine import simplify_closed
from garment_engine import deserialize
from engineering.native import readback, assembly_readback
from semantic_patterns import describe


# Only documented, individually readable/settable properties. No guessed native state.
PROPERTIES = (
    ('fabric_index', 'GetPatternPieceFabricIndex', 'SetPatternPieceFabricIndex'),
    ('layer', 'GetPatternLayer', 'SetPatternLayer'),
    ('particle_distance_mm', 'GetParticleDistanceOfPattern', 'SetParticleDistanceOfPattern'),
    ('grain_link_all_colorways', 'IsPatternPieceGrainLinkAllColorways', 'SetPatternPieceGrainLinkAllColorways'),
    ('grain_direction_deg', 'GetPatternPieceGrainDirection', 'SetPatternPieceGrainDirection'),
    ('name', 'GetPatternPieceName', 'SetPatternPieceName'),
)
PROPERTY_LABELS = {'fabric_index': 'ткань', 'layer': 'слой', 'particle_distance_mm': 'размер сетки',
                   'grain_link_all_colorways': 'связь долевой между цветовыми вариантами',
                   'grain_direction_deg': 'направление долевой', 'name': 'название'}


def same_piece(a, b):
    def comparable(p):
        result = {k: v for k, v in p.items() if k != 'construction_version'}
        # Link IDs can be regenerated by a constructor without moving a mark.
        # The exporter uses segment/t/kind, never sewing_id, to draw its geometry.
        result['notches'] = [{k: v for k, v in n.items() if k != 'sewing_id'} for n in p.get('notches', [])]
        return result
    return comparable(a) == comparable(b)


def capture_properties(api, index):
    values, unavailable = {}, []
    for key, getter, setter in PROPERTIES:
        if not all(callable(getattr(api, name, None)) for name in (getter, setter)):
            unavailable.append(key)
            continue
        value = getattr(api, getter)(index)
        if value is None or isinstance(value, (int, float)) and not math.isfinite(value):
            raise ValueError('Не удалось прочитать свойство детали: ' + PROPERTY_LABELS[key])
        values[key] = value
    return {'values': values, 'unavailable': unavailable}


def restore_properties(api, index, captured, old, new):
    values = dict(captured['values'])
    # An explicit material change wins over preservation; an unchanged model must
    # retain the fabric the user actually assigned in CLO.
    if old.get('material') != new.get('material') and 'fabric_index' in new.get('material', {}):
        if 'fabric_index' not in values:
            raise ValueError('CLO не позволяет проверить изменение ткани; исходная деталь сохранена')
        values['fabric_index'] = new['material']['fabric_index']
    if old['name'] != new['name'] and 'name' in values:
        values['name'] = new['name']
    for key, getter, setter in PROPERTIES:
        if key in values:
            getattr(api, setter)(index, values[key])
    for key, getter, setter in PROPERTIES:
        if key not in values:
            continue
        actual, expected = getattr(api, getter)(index), values[key]
        if isinstance(expected, float):
            error = abs(actual - expected) if isinstance(actual, (int, float)) else float('inf')
            if key == 'grain_direction_deg' and math.isfinite(error):
                error = abs((actual - expected + 180) % 360 - 180)
            matched = math.isfinite(error) and error <= .001
        else:
            matched = actual == expected
        if not matched:
            raise ValueError('CLO не подтвердил перенос свойства «{}» для детали «{}»'.format(PROPERTY_LABELS[key], new['name']))
    return {'status': 'verified' if values else 'unavailable',
            'values': values, 'unavailable': captured['unavailable']}


def existing_result(api, index, piece, spec):
    """Verify the source model and infer its translation, including legacy export."""
    from clo_operations import info
    raw = api.GetPatternInputInformation(index)
    raw = json.loads(raw) if isinstance(raw, str) else raw
    actual = [(float(p['Point positionX']), float(p['Point positionY']))
              for p in raw['Pattern InputInformation'][0]['PointList'] if 'Point positionX' in p]
    contour = deserialize(piece['cut_contour'])
    local = encode(contour, True)['anchors']
    local = [(x, -y) for x, y in local]
    if len(local) != len(actual):
        local = [(x, -y) for x, y, _ in simplify_closed(contour.clo_points(.1), .08)]
    if not actual or len(actual) != len(local):
        raise ValueError('Не удалось сопоставить сохранённый контур: ' + piece['name'])
    dx, dy = actual[0][0] - local[0][0], actual[0][1] - local[0][1]
    measured = readback(api, index, [(x + dx, y + dy) for x, y in local], piece)
    lengths = [api.GetLineLength(index, i) for i in range(len(actual))]
    return (dx, dy), {
        'pattern_index': index, 'clo_pattern_id': info(api, index)['id'],
        'native_measurement': measured, 'semantic': describe(spec, contour),
        'production': spec['production'], 'name': {'status': 'preserved'},
        'internal_lines': {'status': 'preserved', 'note': 'Нативная деталь сохранена без пересоздания'},
        'material': {'status': 'preserved'}, 'segments': len(actual),
        'perimeter_mm': sum(lengths), 'analytic_perimeter_mm': contour.perimeter(),
        'update': 'reused',
    }


def update_garment(job, api, exporter, report):
    try:
        return _update_garment(job, api, exporter, report)
    except Exception as error:
        if not hasattr(error, 'transaction'):
            error.transaction = {'stage': 'update_preflight_failed', 'requires_manual_recovery': False,
                                 'note': 'Проверка остановлена до изменения проекта'}
        raise


def _update_garment(job, api, exporter, report):
    from clo_operations import locate, snapshot, fingerprint, info
    old = job['previous_pieces']
    pieces, specs, targets = job['garment']['pieces'], job['patterns'], job['replace_targets']
    if not isinstance(old, list) or len(old) != len(targets):
        raise ValueError('Неполная предыдущая модель изделия; обновление остановлено')
    if len({p['id'] for p in old}) != len(old) or len({p['id'] for p in pieces}) != len(pieces):
        raise ValueError('Повтор ID в предыдущей модели изделия')
    previous = {p['id']: i for i, p in enumerate(old)}
    for b, spec in zip(pieces, specs):
        if (spec['semantic']['id'] != b['id'] or
                b['id'] in previous and old[previous[b['id']]]['role'] != b['role']):
            raise ValueError('Привязки деталей не соответствуют сохранённой модели')
    indices = [locate(api, t) for t in targets]
    if len(set(indices)) != len(indices):
        raise ValueError('Повтор целевой детали')
    before = snapshot(api)
    changed = [i for i, b in enumerate(pieces) if b['id'] not in previous or not same_piece(old[previous[b['id']]], b)]
    kept_ids = {p['id'] for p in pieces}
    replaced_ids = {pieces[i]['id'] for i in changed}
    removed_indices = [index for p, index in zip(old, indices) if p['id'] not in kept_ids or p['id'] in replaced_ids]
    offsets, source_results, properties = {}, {}, {}
    # Complete every source check and capture before creating anything.
    for i, (piece, index) in enumerate(zip(old, indices)):
        spec = {'type': 'garment_piece', 'name': piece['name'], 'segments': piece['cut_contour'],
                'production': piece, 'semantic': {'id': piece['id'], 'garment_id': job['garment']['id']}}
        offset, result = existing_result(api, index, piece, spec)
        offsets[piece['id']] = offset
        source_results[piece['id']] = result
        if piece['id'] in replaced_ids:
            properties[piece['id']] = capture_properties(api, index)
    results = [source_results.get(p['id']) for p in pieces]
    for p, spec, result in zip(pieces, specs, results):
        if result is not None:
            result['production'] = p
            result['semantic'] = describe(spec, deserialize(p['cut_contour']))
    created, backup = [], None
    try:
        if removed_indices and not changed:
            backup = backup_project(exporter)
        if changed:
            staged = create_batch(dict(job, patterns=[specs[i] for i in changed],
                                       translations=[offsets.get(pieces[i]['id']) for i in changed]), api, exporter)
            backup = staged['backup']
            created = staged['patterns']
            for i, result in zip(changed, created):
                identity = pieces[i]['id']
                if identity in previous:
                    result['preserved_properties'] = restore_properties(api, result['pattern_index'], properties[identity], old[previous[identity]], pieces[i])
                    result['update'] = 'replaced'
                else:
                    result['update'] = 'added'
                results[i] = result
        report['native_export'] = assembly_readback(job['garment'], results, report)
        if any(s['passed'] is False for s in report['native_export']['seams']):
            raise ValueError('Фактические длины швов CLO не прошли проверку')
        staged_snapshot = snapshot(api)
        if any(staged_snapshot.get(k) != v for k, v in before.items()):
            raise ValueError('Исходные детали изменились во время подготовки обновления')
    except Exception as error:
        created_ids = {r['clo_pattern_id'] for r in created}
        for index in range(api.GetPatternCount() - 1, -1, -1):
            if info(api, index)['id'] in created_ids:
                try:
                    api.DeletePatternPiece(index)
                except Exception:
                    break
        recovered = snapshot(api) == before
        # create_batch owns its own rollback if it failed before returning.
        prior = getattr(error, 'transaction', {})
        error.transaction = {'stage': 'update_staging_failed', 'backup': backup or prior.get('backup'),
                             'requires_manual_recovery': not recovered,
                             'note': 'Исходные детали не удалялись; новые детали отменены' if recovered else 'Проверьте проект и резервную копию'}
        raise
    if removed_indices:
        try:
            for index in sorted(removed_indices, reverse=True):
                api.DeletePatternPiece(index)
        except Exception as error:
            error.transaction = {'stage': 'replacement_partial', 'backup': backup, 'requires_manual_recovery': True,
                                 'note': 'Удаление исходных деталей завершилось частично. Восстановите резервную копию'}
            raise
    try:
        current = {info(api, i)['id']: i for i in range(api.GetPatternCount())}
        after = snapshot(api)
        removed = {str(t['pattern_id']) for t, index in zip(targets, indices) if index in removed_indices}
        if (any(after.get(k) != v for k, v in before.items() if k not in removed) or
                len(after) != len(before) + len(pieces) - len(old) or any(k in after for k in removed)):
            raise ValueError('Проверка выборочного обновления не пройдена; восстановите резервную копию')
        for result in results:
            result['pattern_index'] = current[result['clo_pattern_id']]
            result['fingerprint'] = fingerprint(api, result['pattern_index'])
    except Exception as error:
        error.transaction = {'stage': 'replacement_verification_failed', 'backup': backup, 'requires_manual_recovery': bool(changed or removed_indices)}
        raise
    return {'patterns': results, 'backup': backup, 'qa_report': report,
            'update_summary': {'replaced': sum(p['update'] == 'replaced' for p in results),
                               'added': sum(p['update'] == 'added' for p in results),
                               'removed': sum(p['id'] not in kept_ids for p in old),
                               'reused': len(pieces) - len(changed),
                               'sewing': 'replaced_pieces_require_resewing' if changed or removed_indices else 'native_objects_unchanged',
                               'note': 'Швы заменённых деталей, ручные линии и положение в 3D автоматически не восстанавливаются' if changed or removed_indices else 'Все нативные детали сохранены'}}
